/**
 * Returns the post in the requested language (English posts are returned as is). Works for full posts and for
 * trimmed cards (only the fields the card already has are replaced).
 */
export function localizePost<T extends { slug: string }>(post: T, lang: Lang): T {
  if (lang !== "ar") return post;
  const translated = postsAr[post.slug];
  if (!translated) return post;
  const merged: Record<string, unknown> = { ...post };
  for (const [key, value] of Object.entries(translated)) {
    if (key in post && value) merged[key] = value;
  }
  return merged as T;
}

